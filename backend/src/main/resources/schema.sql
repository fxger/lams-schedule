-- =====================================================================
-- 实验室排课系统 · H2 建表脚本（每次启动执行，IF NOT EXISTS 保证幂等）
-- 表：users / laboratories / courses / course_students / schedules
-- =====================================================================

CREATE TABLE IF NOT EXISTS users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(50)  NOT NULL,
    password     VARCHAR(100) NOT NULL,
    real_name    VARCHAR(50),
    user_type    VARCHAR(20)  NOT NULL,          -- admin / student
    status       INT          DEFAULT 1,
    created_time TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_username ON users (username);

CREATE TABLE IF NOT EXISTS laboratories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    description  VARCHAR(255),
    location     VARCHAR(100),
    room_number  INT,
    capacity     INT          NOT NULL,
    status       INT          DEFAULT 1,
    created_time TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS courses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    code         VARCHAR(50),
    semester     VARCHAR(20),
    credits      INT          DEFAULT 3,
    weeks        INT          DEFAULT 8,          -- 该课程需要安排的总周数（1..weeks）
    periods      INT          DEFAULT 2,          -- 每周连续上的节数
    description  VARCHAR(500),
    status       INT          DEFAULT 1,
    created_time TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS course_students (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id  BIGINT NOT NULL,
    student_id BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_course_students ON course_students (course_id, student_id);

CREATE TABLE IF NOT EXISTS schedules (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week         INT          NOT NULL,           -- 1..16
    day          INT          NOT NULL,           -- 1..7 周一..周日
    section      INT          NOT NULL,           -- 1..11 节次
    course_id    BIGINT,
    course_name  VARCHAR(100),
    lab_id       BIGINT       NOT NULL,
    lab_name     VARCHAR(100),
    created_by   VARCHAR(50),
    updated_by   VARCHAR(50),
    created_time TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);
-- 同一实验室、同一时间只能有一条排课（数据库层兜底）
CREATE UNIQUE INDEX IF NOT EXISTS uk_schedules_slot ON schedules (week, day, section, lab_id);
CREATE INDEX IF NOT EXISTS idx_schedules_week ON schedules (week);
